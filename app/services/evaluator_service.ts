/**
 * EvaluatorService — LLM-as-judge for the chatbot agent.
 *
 * Runs asynchronously (fire-and-forget) after the agent responds.
 * Adds two scores to the Langfuse trace:
 *  - sql_correctness: does the generated SQL answer the question?
 *  - answer_relevance: does the final text answer address the question?
 */

import { BedrockRuntimeClient, InvokeModelCommand } from '@aws-sdk/client-bedrock-runtime'
import env from '#start/env'
import langfuse from '#services/langfuse_client'

const MODEL_ID = 'eu.anthropic.claude-sonnet-4-5-20250929-v1:0'

function getClient(): BedrockRuntimeClient {
  return new BedrockRuntimeClient({
    region: env.get('AWS_REGION'),
    credentials: {
      accessKeyId: env.get('AWS_ACCESS_KEY'),
      secretAccessKey: env.get('AWS_SECRET_KEY'),
    },
  })
}

async function callClaude(prompt: string): Promise<{ score: number; reason: string }> {
  const client = getClient()
  const body = {
    anthropic_version: 'bedrock-2023-05-31',
    max_tokens: 256,
    messages: [{ role: 'user', content: prompt }],
  }

  const command = new InvokeModelCommand({
    modelId: MODEL_ID,
    contentType: 'application/json',
    accept: 'application/json',
    body: JSON.stringify(body),
  })

  const raw = await client.send(command)
  const json = JSON.parse(Buffer.from(raw.body).toString('utf-8'))
  const text = json.content?.[0]?.text ?? '{}'

  // Extract JSON from response (Claude may wrap it in markdown)
  const match = text.match(/\{[\s\S]*\}/)
  if (!match) return { score: 0, reason: 'Could not parse evaluator response' }

  const parsed = JSON.parse(match[0])
  return {
    score: Math.min(1, Math.max(0, Number(parsed.score) || 0)),
    reason: String(parsed.reason ?? ''),
  }
}

/**
 * Evaluates the SQL generated by the agent.
 * Scores 0-1: 1 = SQL correctly answers the question, 0 = wrong/irrelevant.
 */
async function evaluateSql(
  question: string,
  sql: string
): Promise<{ score: number; reason: string }> {
  const prompt = `You are evaluating the quality of a SQL query generated by an AI assistant.

User question: "${question}"
Generated SQL:
\`\`\`sql
${sql}
\`\`\`

Evaluate if this SQL query is correct and would return the relevant data to answer the question.
Score from 0 to 1:
- 1.0 = SQL is well-formed, targets the right tables/columns, and would return the correct data
- 0.5 = SQL is partially correct (right tables but wrong filters, missing joins, etc.)
- 0.0 = SQL is wrong, targets wrong tables, or would not answer the question

Respond ONLY with a JSON object: {"score": 0.0, "reason": "brief explanation in one sentence"}`

  return callClaude(prompt)
}

/**
 * Evaluates the relevance of the agent's final text answer.
 * Scores 0-1: 1 = answer directly addresses the question, 0 = irrelevant/off-topic.
 */
async function evaluateAnswerRelevance(
  question: string,
  answer: string
): Promise<{ score: number; reason: string }> {
  const prompt = `You are evaluating the quality of an AI assistant's response.

User question: "${question}"
AI answer: "${answer}"

Evaluate if the answer is relevant and directly addresses the question.
Score from 0 to 1:
- 1.0 = Answer directly and completely addresses the question
- 0.5 = Answer is partially relevant but misses key aspects
- 0.0 = Answer is irrelevant, off-topic, or doesn't address the question

Respond ONLY with a JSON object: {"score": 0.0, "reason": "brief explanation in one sentence"}`

  return callClaude(prompt)
}

/**
 * Runs all evaluations for a chatbot turn and pushes scores to Langfuse.
 * Designed to be called fire-and-forget — never throws.
 */
export async function evaluate({
  traceId,
  question,
  answer,
  executedSql,
}: {
  traceId: string
  question: string
  answer: string
  executedSql: Array<{ question: string; sql: string }>
}): Promise<void> {
  try {
    const scores: Promise<unknown>[] = []

    // Score each generated SQL
    for (const { sql } of executedSql) {
      scores.push(
        evaluateSql(question, sql).then(({ score, reason }) =>
          langfuse.score({
            traceId,
            name: 'sql_correctness',
            value: score,
            comment: reason,
          })
        )
      )
    }

    // Score answer relevance
    scores.push(
      evaluateAnswerRelevance(question, answer).then(({ score, reason }) =>
        langfuse.score({
          traceId,
          name: 'answer_relevance',
          value: score,
          comment: reason,
        })
      )
    )

    await Promise.all(scores)
    await langfuse.flushAsync()
  } catch {
    // Silently ignore — evaluation must never affect the user response
  }
}
