export function resolveMigrators(onlyTable?: string): { name: string; migrate: MigratorFn }[] {
  if (!onlyTable) return MIGRATION_ORDER

  const normalized = MYSQL_ALIASES[onlyTable] ?? onlyTable
  const match = MIGRATION_ORDER.filter((m) => m.name === normalized)

  return match
}

